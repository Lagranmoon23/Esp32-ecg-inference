"""Export preprocessing constants and three host-referenced golden vectors.

Run this script on the server from the software directory.  It reads only
already-created artifacts; it does not train or evaluate a model.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
from scipy import signal


def cpp_float(value: float) -> str:
    value = float(value)
    if not np.isfinite(value):
        raise ValueError(f"Non-finite firmware constant: {value}")
    text = f"{value:.10g}"
    if "e" not in text.lower() and "." not in text:
        text += ".0"
    return text + "f"


def cpp_row(values: np.ndarray, indent: str = "    ") -> str:
    return indent + "{{" + ", ".join(cpp_float(v) for v in values) + "}}"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--splits", default="patient_independent_hierarchical_splits.npz"
    )
    parser.add_argument(
        "--golden", default="deployment_artifacts/stage1_golden_vectors.npz"
    )
    parser.add_argument("--output", default="ecg_generated_config.hpp")
    args = parser.parse_args()

    with np.load(args.splits) as split:
        rr_mean = split["rr_mean"].astype(np.float64).reshape(6)
        rr_std = split["rr_std"].astype(np.float64).reshape(6)
    if np.any(rr_std <= 0):
        raise ValueError(f"Invalid RR standard deviations: {rr_std}")

    with np.load(args.golden) as golden:
        beats_all = golden["x1"].astype(np.float64).reshape(-1, 198)
        rr_all = golden["x2"].astype(np.float64).reshape(-1, 6)
        labels_all = golden["labels"].astype(np.int64).reshape(-1)
        if "reference_quant_type" not in golden.files:
            raise ValueError(
                "This is a pre-quantization golden file. Use "
                "stage1_golden_vectors_w16a16.npz generated by the updated "
                "stage1_espdl_quantize.py."
            )
        reference_quant_type = str(golden["reference_quant_type"].item())
        if "logits" not in golden.files:
            raise ValueError(
                "Golden file has no 'logits'. Re-run stage1_deployment_audit.py "
                "with the frozen model used to build the deploy ONNX."
            )
        logits_all = golden["logits"].astype(np.float64).reshape(-1, 3)
        predictions_all = (
            golden["predictions"].astype(np.int64).reshape(-1)
            if "predictions" in golden.files
            else np.argmax(logits_all, axis=1).astype(np.int64)
        )

    row_count = len(labels_all)
    if not (
        len(beats_all)
        == len(rr_all)
        == len(logits_all)
        == len(predictions_all)
        == row_count
    ):
        raise ValueError("Golden arrays have inconsistent row counts")

    # Export the complete frozen golden set. Deployment equivalence is measured
    # by host/device prediction agreement, independently of ground-truth accuracy.
    selected = np.arange(row_count, dtype=np.int64)
    for class_id in range(3):
        if not np.any(labels_all == class_id):
            raise ValueError(f"Golden vectors contain no class {class_id} samples")
    beats = beats_all[selected]
    rr = rr_all[selected]
    labels = labels_all[selected]
    reference_logits = logits_all[selected]
    reference_predictions = predictions_all[selected]

    fs = 360
    bandpass = signal.butter(
        4, [0.5, 40.0], btype="bandpass", fs=fs, output="sos"
    )
    notch_b, notch_a = signal.iirnotch(50.0, 30.0, fs=fs)
    sos = np.vstack([bandpass, signal.tf2sos(notch_b, notch_a)])
    if sos.shape != (5, 6):
        raise AssertionError(f"Unexpected SOS shape: {sos.shape}")
    if not np.allclose(sos[:, 3], 1.0):
        raise AssertionError("SOS rows must be normalized to a0=1")
    zi = signal.sosfilt_zi(sos)

    lines = [
        "#pragma once",
        "",
        "// Generated by tools/export_firmware_assets.py; do not hand-edit.",
        "#include <array>",
        "#include <cstddef>",
        "",
        "#define ECG_GENERATED_HAS_REFERENCE_LOGITS 1",
        "",
        "namespace ecg::generated {",
        "inline constexpr bool kReady = true;",
        "inline constexpr int kSampleRateHz = 360;",
        f"inline constexpr std::size_t kFilterSections = {len(sos)};",
        "inline constexpr std::array<std::array<float, 6>, kFilterSections> kFilterSos{{",
    ]
    lines.extend(cpp_row(row) + "," for row in sos)
    lines.extend(
        [
            "}};",
            "inline constexpr std::array<std::array<float, 2>, kFilterSections> kFilterZi{{",
        ]
    )
    lines.extend(cpp_row(row) + "," for row in zi)
    lines.extend(
        [
            "}};",
            "inline constexpr std::array<float, 6> kRrMean" + cpp_row(rr_mean, "") + ";",
            "inline constexpr std::array<float, 6> kRrStd" + cpp_row(rr_std, "") + ";",
            f"inline constexpr std::size_t kGoldenCount = {len(selected)};",
            "inline constexpr std::array<std::array<float, 198>, kGoldenCount> kGoldenBeats{{",
        ]
    )
    lines.extend(cpp_row(row) + "," for row in beats)
    lines.extend(
        [
            "}};",
            "inline constexpr std::array<std::array<float, 6>, kGoldenCount> kGoldenRr{{",
        ]
    )
    lines.extend(cpp_row(row) + "," for row in rr)
    lines.extend(
        [
            "}};",
            "inline constexpr std::array<int, kGoldenCount> kGoldenLabels{{"
            + ", ".join(str(int(v)) for v in labels)
            + "}};",
            "inline constexpr std::array<std::array<float, 3>, kGoldenCount> "
            "kGoldenReferenceLogits{{",
        ]
    )
    lines.extend(cpp_row(row) + "," for row in reference_logits)
    lines.extend(
        [
            "}};",
            "inline constexpr std::array<int, kGoldenCount> "
            "kGoldenReferencePredictions{{"
            + ", ".join(str(int(v)) for v in reference_predictions)
            + "}};",
            "inline constexpr float kGoldenLogitAbsTolerance = 0.15f;",
            "}  // namespace ecg::generated",
            "",
        ]
    )

    output = Path(args.output).resolve()
    output.write_text("\n".join(lines), encoding="utf-8")
    print(f"Generated: {output}")
    print("Golden labels:", labels.tolist())
    print("Golden reference predictions:", reference_predictions.tolist())
    print("Golden reference quantization:", reference_quant_type)
    print("Golden sample count:", len(selected))
    print("Golden reference logits:")
    print(reference_logits.astype(np.float32))
    print("RR mean:", rr_mean.tolist())
    print("RR std:", rr_std.tolist())


if __name__ == "__main__":
    main()
